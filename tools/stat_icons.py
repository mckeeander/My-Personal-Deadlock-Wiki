#!/usr/bin/env python3
"""Fetch the game's own property icons and inline them into index.html as the SIG block.

The icons are the same set the deadlock.wiki Stats table uses. They are flattened to
currentColor so the section tints (vitality green, weapon orange, spirit purple) still apply.
Run:  python3 tools/stat_icons.py
"""
import re, sys, urllib.request, pathlib

BASE = "https://assets-bucket.deadlock-api.com/assets-api-res/icons/icons/properties/"
# SI key used by siIcon()  ->  game icon file
MAP = {
    "health": "health", "regen": "health_regen", "boot": "move_speed", "sprint": "move_sprint",
    "dash": "move_dash", "stamina": "move_stamina", "stamrech": "move_stamina_recharge",
    "dmg": "damage_bullet_color", "ammo": "ammo_clip_size", "bps": "fire_rate",
    "reload": "ammo_reload", "vel": "bullet_velocity", "fist": "melee", "star": "spirit",
    "bshield": "armor_bullet_color", "sshield": "armor_spirit_color",
}
# Two-colour icons: only this fill is tinted, everything else keeps the game's colour
PARTIAL = {"bshield": "#00FF99", "sshield": "#00FF99"}
HTML = pathlib.Path(__file__).resolve().parent.parent / "index.html"

def fetch(name):
    req = urllib.request.Request(BASE + name + ".svg", headers={"User-Agent": "personal-wiki-icon-sync"})
    return urllib.request.urlopen(req, timeout=30).read().decode()

def flatten(svg, tint=None):
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r'\s(width|height)="[^"]*"', "", inner)
    if tint:
        inner = inner.replace('fill="%s"' % tint, 'fill="currentColor"')
    else:
        inner = re.sub(r'(fill|stroke)="(?!none)[^"]*"', lambda m: m.group(1) + '="currentColor"', inner)
    return re.sub(r"\s+", " ", inner).strip().replace("> <", "><")

def main():
    lines = []
    for key, name in MAP.items():
        body = flatten(fetch(name), PARTIAL.get(key))
        lines.append("  %s: '<svg viewBox=\"0 0 128 128\" width=\"24\" height=\"24\" stroke=\"none\">%s</svg>'" % (key, body.replace("'", "\\'")))
    block = "// SIG-BEGIN (generated by tools/stat_icons.py)\nvar SIG = {\n" + ",\n".join(lines) + "\n};\n// SIG-END"
    src = HTML.read_text()
    if "// SIG-BEGIN" in src:
        src = re.sub(r"// SIG-BEGIN.*?// SIG-END", lambda m: block, src, flags=re.S)
    else:
        src = src.replace("function siIcon(n) {", block + "\nfunction siIcon(n) {", 1)
    HTML.write_text(src)
    print("wrote %d icons, %d bytes" % (len(MAP), len(block)))

if __name__ == "__main__":
    sys.exit(main())
